export function makeProject(title: string, person: string, type: string) {
  return {
    id: crypto.randomUUID(),
    title,
    person,
    type,
    demo: false,
    chapters: templates[type].map((title, i) => ({
      id: "c" + i,
      title,
      progress: 0,
      text: "",
      kind: "Section rédigée",
      links: [],
      sections: [],
    })),
    materials: [],
    tasks: [],
    dates: [],
    comments: [],
    versions: [],
  };
}
